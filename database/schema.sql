-- =========================================
-- Student Attendance Management System
-- Database Schema for Supabase PostgreSQL
-- =========================================

-- 1. Create Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    class_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Create Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL
        REFERENCES public.students(id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(10) NOT NULL
        CHECK (status IN ('Present', 'Absent')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- A student can have only one attendance record per day
    CONSTRAINT unique_student_attendance
        UNIQUE (student_id, attendance_date),

    -- Prevent attendance dates in the future
    CONSTRAINT attendance_date_not_future
        CHECK (attendance_date <= CURRENT_DATE)
);

-- 3. Create Indexes for Faster Queries
CREATE INDEX IF NOT EXISTS idx_students_class
    ON public.students(class_name);

CREATE INDEX IF NOT EXISTS idx_students_active
    ON public.students(is_active);

CREATE INDEX IF NOT EXISTS idx_attendance_date
    ON public.attendance(attendance_date);

CREATE INDEX IF NOT EXISTS idx_attendance_student
    ON public.attendance(student_id);

-- 4. Enable Row Level Security
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;

-- =========================================
-- Schema setup complete
